import 'package:cipta_vera_mandiri_digital/app/services/face_recognition_service.dart';
import 'package:cipta_vera_mandiri_digital/app/services/chat_notification_service.dart';
import 'package:cipta_vera_mandiri_digital/app/services/app_notification_service.dart';
import 'package:cipta_vera_mandiri_digital/app/services/notification_service.dart';
import 'package:cipta_vera_mandiri_digital/app/services/push_notification_service.dart';
import 'package:cipta_vera_mandiri_digital/app/services/user_activity_notification_service.dart';

late final List<CameraDescription> cameras;

void main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await AppPreferences.init();
  cameras = await availableCameras();
  await dotenv.load(fileName: ".env");
  // Debug: verify env values are loaded
  debugPrint('ENV IOS_APP_ID: ${dotenv.env['IOS_APP_ID'] ?? 'NULL'}');
  debugPrint('ENV IOS_PROJECT_ID: ${dotenv.env['IOS_PROJECT_ID'] ?? 'NULL'}');
  try {
    await Firebase.initializeApp(
      options: DefaultFirebaseOptions.currentPlatform,
    );
    if (!kIsWeb) {
      FirebaseFirestore.instance.settings = const Settings(
        persistenceEnabled: true,
        cacheSizeBytes: Settings.CACHE_SIZE_UNLIMITED,
      );
    }
    debugPrint(
      '✅ Firebase initialized with projectId=${DefaultFirebaseOptions.currentPlatform.projectId}, appId=${DefaultFirebaseOptions.currentPlatform.appId}',
    );

    try {
      await FirebaseAppCheck.instance.activate(
        providerAndroid: kDebugMode
            ? const AndroidDebugProvider()
            : const AndroidPlayIntegrityProvider(),
        providerApple: kDebugMode
            ? const AppleDebugProvider()
            : const AppleDeviceCheckProvider(),
      );
      debugPrint('✅ Firebase App Check initialized');
    } catch (appCheckError, appCheckStackTrace) {
      debugPrint('⚠️ Firebase App Check init failed: $appCheckError');
      debugPrint(appCheckStackTrace.toString());
    }
  } catch (e, st) {
    debugPrint('❌ Firebase init failed: $e');
    debugPrint(st.toString());
  }

  // Initialize FaceRecognitionService
  await FaceRecognitionService().init();
  await NotificationService().init();
  await PushNotificationService().init();
  ChatNotificationService().start();
  await AppNotificationService().start();
  UserActivityNotificationService().start();

  runApp(
    GetMaterialApp(
      debugShowCheckedModeBanner: false,
      initialRoute: Routes.SPLASH,
      getPages: AppPages.routes,
    ),
  );
}
